/**
 * Builds `tokens.css`. Dark mode applies with the `.dark` class (shadcn convention)
 * or automatically with `prefers-color-scheme: dark`, unless the page sets `.light`.
 */
export function buildTokensCss(): string {
  const themeLines = colorTokenNames.map((name) => `  --color-akso-${name}: var(--akso-${name});`);
  return [
    "/* Generated by packages/core/scripts/generate-tokens-css.ts. Do not edit by hand. */",
    "",
    block(":root", colors.light),
    "",
    block(".dark", colors.dark),
    "",
    "@media (prefers-color-scheme: dark) {",
    block(":root:not(.light)", colors.dark, "  "),
    "}",
    "",
    "/* Tailwind CSS v4: exposes the tokens as utilities such as bg-akso-surface. */",
    "@theme inline {",
    ...themeLines,
    "}",
    "",
    utilitiesCss,
  ].join("\n");
}
